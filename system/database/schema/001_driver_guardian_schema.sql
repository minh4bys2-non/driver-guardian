CREATE TABLE DRIVERS (
    DRIVER_ID       NUMBER GENERATED BY DEFAULT AS IDENTITY,
    DRIVER_CODE     VARCHAR2(30) NOT NULL,
    FULL_NAME       VARCHAR2(100) NOT NULL,
    PHONE_NUMBER    VARCHAR2(20),
    LICENSE_NUMBER  VARCHAR2(50),
    STATUS          VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
    CREATED_AT      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT PK_DRIVERS PRIMARY KEY (DRIVER_ID),
    CONSTRAINT UQ_DRIVERS_CODE UNIQUE (DRIVER_CODE),
    CONSTRAINT CK_DRIVERS_STATUS
        CHECK (STATUS IN ('ACTIVE', 'INACTIVE'))
);


CREATE TABLE VEHICLES (
    VEHICLE_ID      NUMBER GENERATED BY DEFAULT AS IDENTITY,
    PLATE_NUMBER    VARCHAR2(20) NOT NULL,
    VEHICLE_NAME    VARCHAR2(100),
    VEHICLE_TYPE    VARCHAR2(50),
    DEVICE_CODE     VARCHAR2(50),
    STATUS          VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
    CREATED_AT      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT PK_VEHICLES PRIMARY KEY (VEHICLE_ID),
    CONSTRAINT UQ_VEHICLES_PLATE UNIQUE (PLATE_NUMBER),
    CONSTRAINT UQ_VEHICLES_DEVICE UNIQUE (DEVICE_CODE),
    CONSTRAINT CK_VEHICLES_STATUS
        CHECK (STATUS IN ('ACTIVE', 'INACTIVE', 'MAINTENANCE'))
);


CREATE TABLE MODEL_VERSIONS (
    MODEL_VERSION_ID  NUMBER GENERATED BY DEFAULT AS IDENTITY,
    VERSION_NAME      VARCHAR2(50) NOT NULL,
    MODEL_TYPE        VARCHAR2(50),
    FILE_NAME         VARCHAR2(255),
    DESCRIPTION       VARCHAR2(500),
    IS_ACTIVE         CHAR(1) DEFAULT 'Y' NOT NULL,
    DEPLOYED_AT       TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT PK_MODEL_VERSIONS PRIMARY KEY (MODEL_VERSION_ID),
    CONSTRAINT UQ_MODEL_VERSION_NAME UNIQUE (VERSION_NAME),
    CONSTRAINT CK_MODEL_ACTIVE
        CHECK (IS_ACTIVE IN ('Y', 'N'))
);


CREATE TABLE DRIVING_SESSIONS (
    SESSION_ID         NUMBER GENERATED BY DEFAULT AS IDENTITY,
    DRIVER_ID          NUMBER NOT NULL,
    VEHICLE_ID         NUMBER NOT NULL,
    MODEL_VERSION_ID   NUMBER,
    START_TIME         TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    END_TIME           TIMESTAMP,
    DURATION_SECONDS   NUMBER DEFAULT 0 NOT NULL,
    TOTAL_ALERTS       NUMBER DEFAULT 0 NOT NULL,
    SAFETY_SCORE       NUMBER(5,2),
    STATUS             VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
    SYNC_STATUS        VARCHAR2(20) DEFAULT 'SYNCED' NOT NULL,
    CREATED_AT         TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT PK_DRIVING_SESSIONS PRIMARY KEY (SESSION_ID),

    CONSTRAINT FK_SESSION_DRIVER
        FOREIGN KEY (DRIVER_ID)
        REFERENCES DRIVERS (DRIVER_ID),

    CONSTRAINT FK_SESSION_VEHICLE
        FOREIGN KEY (VEHICLE_ID)
        REFERENCES VEHICLES (VEHICLE_ID),

    CONSTRAINT FK_SESSION_MODEL
        FOREIGN KEY (MODEL_VERSION_ID)
        REFERENCES MODEL_VERSIONS (MODEL_VERSION_ID),

    CONSTRAINT CK_SESSION_STATUS
        CHECK (STATUS IN ('ACTIVE', 'COMPLETED', 'CANCELLED')),

    CONSTRAINT CK_SESSION_SYNC
        CHECK (SYNC_STATUS IN ('PENDING', 'SYNCED', 'FAILED')),

    CONSTRAINT CK_SESSION_SCORE
        CHECK (SAFETY_SCORE IS NULL OR SAFETY_SCORE BETWEEN 0 AND 100)
);


CREATE TABLE DROWSINESS_EVENTS (
    EVENT_ID          NUMBER GENERATED BY DEFAULT AS IDENTITY,
    SESSION_ID        NUMBER NOT NULL,
    EVENT_TIME        TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    DRIVER_STATE      VARCHAR2(20) NOT NULL,
    ALERT_LEVEL       NUMBER(1) DEFAULT 0 NOT NULL,
    CONFIDENCE        NUMBER(6,5),
    DROWSINESS_SCORE  NUMBER(5,2),
    EAR_VALUE         NUMBER(7,5),
    MAR_VALUE         NUMBER(7,5),
    HEAD_POSE         VARCHAR2(50),
    DURATION_MS       NUMBER,
    ACKNOWLEDGED      CHAR(1) DEFAULT 'N' NOT NULL,
    SYNC_STATUS       VARCHAR2(20) DEFAULT 'SYNCED' NOT NULL,
    CREATED_AT        TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT PK_DROWSINESS_EVENTS PRIMARY KEY (EVENT_ID),

    CONSTRAINT FK_EVENT_SESSION
        FOREIGN KEY (SESSION_ID)
        REFERENCES DRIVING_SESSIONS (SESSION_ID),

    CONSTRAINT CK_EVENT_STATE
        CHECK (DRIVER_STATE IN ('NORMAL', 'WARNING', 'DANGER')),

    CONSTRAINT CK_EVENT_ALERT_LEVEL
        CHECK (ALERT_LEVEL BETWEEN 0 AND 2),

    CONSTRAINT CK_EVENT_CONFIDENCE
        CHECK (CONFIDENCE IS NULL OR CONFIDENCE BETWEEN 0 AND 1),

    CONSTRAINT CK_EVENT_ACKNOWLEDGED
        CHECK (ACKNOWLEDGED IN ('Y', 'N')),

    CONSTRAINT CK_EVENT_SYNC
        CHECK (SYNC_STATUS IN ('PENDING', 'SYNCED', 'FAILED'))
);


CREATE TABLE ALERT_ACTIONS (
    ACTION_ID       NUMBER GENERATED BY DEFAULT AS IDENTITY,
    EVENT_ID        NUMBER NOT NULL,
    ACTION_TYPE     VARCHAR2(50) NOT NULL,
    RESPONSE_TYPE   VARCHAR2(50),
    ACTION_TIME     TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    NOTES           VARCHAR2(500),

    CONSTRAINT PK_ALERT_ACTIONS PRIMARY KEY (ACTION_ID),

    CONSTRAINT FK_ACTION_EVENT
        FOREIGN KEY (EVENT_ID)
        REFERENCES DROWSINESS_EVENTS (EVENT_ID),

    CONSTRAINT CK_ACTION_TYPE
        CHECK (
            ACTION_TYPE IN (
                'AUDIO_ALERT',
                'VISUAL_ALERT',
                'NOTIFICATION',
                'DRIVER_CONFIRMATION',
                'ALERT_DISMISSED'
            )
        )
);


