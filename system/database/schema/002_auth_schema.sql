CREATE TABLE USERS (
    USER_ID         NUMBER GENERATED BY DEFAULT AS IDENTITY,
    GOOGLE_SUB      VARCHAR2(255),
    EMAIL           VARCHAR2(255) NOT NULL,
    DISPLAY_NAME    VARCHAR2(100),
    AVATAR_URL      VARCHAR2(500),
    ROLE            VARCHAR2(20) DEFAULT 'DRIVER' NOT NULL,
    DRIVER_ID       NUMBER,
    IS_ACTIVE       CHAR(1) DEFAULT 'Y' NOT NULL,
    CREATED_AT      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    LAST_LOGIN_AT   TIMESTAMP,

    CONSTRAINT PK_USERS PRIMARY KEY (USER_ID),
    CONSTRAINT UQ_USERS_GOOGLE_SUB UNIQUE (GOOGLE_SUB),
    CONSTRAINT UQ_USERS_EMAIL UNIQUE (EMAIL),
    CONSTRAINT FK_USERS_DRIVER
        FOREIGN KEY (DRIVER_ID)
        REFERENCES DRIVERS (DRIVER_ID),
    CONSTRAINT CK_USERS_ROLE
        CHECK (ROLE IN ('DRIVER', 'ADMIN')),
    CONSTRAINT CK_USERS_IS_ACTIVE
        CHECK (IS_ACTIVE IN ('Y', 'N'))
);

CREATE TABLE AUTH_REFRESH_TOKENS (
    TOKEN_ID        NUMBER GENERATED BY DEFAULT AS IDENTITY,
    USER_ID         NUMBER NOT NULL,
    TOKEN_HASH      VARCHAR2(64) NOT NULL,
    DEVICE_INFO     VARCHAR2(255),
    CREATED_AT      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    EXPIRES_AT      TIMESTAMP NOT NULL,
    REVOKED_AT      TIMESTAMP,

    CONSTRAINT PK_AUTH_REFRESH_TOKENS PRIMARY KEY (TOKEN_ID),
    CONSTRAINT FK_REFRESH_USER
        FOREIGN KEY (USER_ID)
        REFERENCES USERS (USER_ID),
    CONSTRAINT UQ_REFRESH_TOKEN_HASH UNIQUE (TOKEN_HASH)
);

CREATE INDEX IDX_USERS_GOOGLE_SUB ON USERS (GOOGLE_SUB);
CREATE INDEX IDX_USERS_EMAIL ON USERS (EMAIL);
CREATE INDEX IDX_USERS_DRIVER_ID ON USERS (DRIVER_ID);
CREATE INDEX IDX_REFRESH_USER_ID ON AUTH_REFRESH_TOKENS (USER_ID);
CREATE INDEX IDX_REFRESH_TOKEN_HASH ON AUTH_REFRESH_TOKENS (TOKEN_HASH);
